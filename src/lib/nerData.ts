function d(
  state_id: string,
  state_name: string,
  name: string,
  lat: number,
  lng: number,
  accessibility_status: District["accessibility_status"],
  risk_score: number,
  population: number,
): District {
  return {
    id: `${state_id}-${name.toLowerCase().replace(/\s+/g, "-")}`,
    state_id,
    state_name,
    name,
    lat,
    lng,
    accessibility_status,
    risk_score,
    population,
    last_updated: minutesAgo(6 + Math.round(risk_score / 6)),
  };
}

